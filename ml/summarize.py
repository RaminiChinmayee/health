"""Write EVALUATION.md from the model cards (numbers are copied from cards, never typed by hand)."""
import json
from pathlib import Path

from common import ARTIFACTS

rows, rejected = [], []
for card_path in sorted(ARTIFACTS.glob("*/*/card.json")):
    c = json.loads(card_path.read_text())
    if c.get("deployable") is False:
        rejected.append(f"- **{c['title']} v{c['version']}** — {c.get('rejection_reason')}")
        continue
    if c["task"] == "binary_classification":
        t = c["evaluation"]["test"]; ci = t.get("ci95", {}); cv = c["evaluation"]["cross_validation_all_data"]
        f = lambda k: f"{t[k]*100:.1f}%" + (f" ({ci[k][0]*100:.0f}–{ci[k][1]*100:.0f})" if k in ci else "")
        rows.append(f"| {c['title']} | v{c['version']} | {c['dataset']['rows_after_dedup']} | {c['algorithm']} | {f('roc_auc')} | {f('recall_sensitivity')} | {f('specificity')} | {f('accuracy')} | {cv['roc_auc']['mean']*100:.1f}% ± {cv['roc_auc']['std']*100:.1f} |")
    else:
        s = c["evaluation"]["selected"]
        rows.append(f"| {c['title']} | v{c['version']} | {c['dataset']['unique_patterns']} unique patterns | {c['algorithm']} | — | top-1 (50% of symptoms): {s['partial_top1']['mean']*100:.1f}% | top-3: {s['partial_top3']['mean']*100:.1f}% | full-symptom top-1: {s['full_top1']['mean']*100:.1f}% | — |")

out = [
    "# Model evaluation summary",
    "",
    "Generated by `ml/summarize.py` from each model's `card.json`; full reports are in `artifacts/<model>/<version>/report.md`.",
    "Binary models: held-out test set (95% bootstrap CI in brackets) and cross-validation over all data.",
    "",
    "| Model | Version | Rows | Algorithm | Test ROC-AUC | Test sensitivity | Test specificity | Test accuracy | CV ROC-AUC |",
    "|---|---|---|---|---|---|---|---|---|",
    *rows,
    "",
    "**Reading these numbers:** they describe performance on each source dataset's population (see each report). They are not clinical validation, and none of these models diagnoses disease. The symptom checker's scores measure agreement with a synthetic disease–symptom table, not diagnostic accuracy in real patients.",
    "",
    "## Rejected models",
    *(rejected or ["- none"]),
]
(Path(__file__).parent / "EVALUATION.md").write_text("\n".join(out) + "\n")
print("\n".join(out))
